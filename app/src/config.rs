//! Generates the engine's `engine.toml` from [`Settings`]. Output is exact:
//! the engine hot-reloads this file, so a stable byte layout avoids churn.

use std::collections::HashSet;
use std::fmt::Write;
use std::fs;

use crate::paths;
use crate::settings::{Layout, RuleAction, Settings};

pub const HEADER: &str = "# Generated by Slat. Edits are overwritten; enable custom config mode to edit by hand.";

/// `%.4f`, trailing zeros stripped, but always at least one decimal.
fn float(x: f64) -> String {
    let mut s = format!("{x:.4}");
    while s.ends_with('0') {
        s.pop();
    }
    if s.ends_with('.') {
        s.push('0');
    }
    s
}

fn quote(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || c as u32 == 0x7f => {
                let _ = write!(out, "\\u{:04X}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn safe_name(bundle_id: &str) -> String {
    if bundle_id.is_empty() {
        return "app".into();
    }
    let body: String = bundle_id
        .to_lowercase()
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { '_' })
        .collect();
    format!("app_{body}")
}

fn bindings(s: &Settings) -> Vec<(String, Vec<String>)> {
    let m = s.mod_key.engine_modifier();
    let sh = format!("{m} + shift");
    let one = |k: &str, mods: &str, key: &str| (k.to_string(), vec![format!("{mods} - {key}")]);
    let two = |k: &str, mods: &str, a: &str, b: &str| {
        (k.to_string(), vec![format!("{mods} - {a}"), format!("{mods} - {b}")])
    };
    // With workspace rows, up and down keep going: within a stack first,
    // then to the row above or below.
    let rows = s.virtual_workspaces_enabled && s.layout() != Layout::Canvas;
    let (north, south) = if rows { ("window_virtualfocus_north", "window_virtualfocus_south") } else { ("window_focus_north", "window_focus_south") };
    let mut out = vec![
        two("window_focus_west", m, "h", "leftarrow"),
        two("window_focus_east", m, "l", "rightarrow"),
        two(north, m, "k", "uparrow"),
        two(south, m, "j", "downarrow"),
        two("window_swap_west", &sh, "h", "leftarrow"),
        two("window_swap_east", &sh, "l", "rightarrow"),
        two("window_swap_north", &sh, "k", "uparrow"),
        two("window_swap_south", &sh, "j", "downarrow"),
        one("window_resize", m, "r"),
        one("window_shrink", &sh, "r"),
        one("window_center", m, "c"),
        one("window_fullwidth", m, "f"),
        one("window_manage", m, "t"),
        one("window_tabbeddisplay", &sh, "t"),
        one("window_stack_west", m, "leftbracket"),
        one("window_stack_east", m, "rightbracket"),
        one("window_unstack_west", &sh, "leftbracket"),
        one("window_unstack_east", &sh, "rightbracket"),
        one("window_nextdisplay", m, "n"),
        one("window_balance", m, "equal"),
    ];
    if s.virtual_workspaces_enabled && s.virtual_workspace_count > 0 {
        let n = s.virtual_workspace_count.min(9);
        out.extend((1..=n).map(|i| one(&format!("window_virtualnum_{i}"), m, &i.to_string())));
        out.extend((1..=n).map(|i| one(&format!("window_virtualmovenum_{i}"), &sh, &i.to_string())));
    }
    out
}

pub fn toml(s: &Settings) -> String {
    let mut o = String::new();
    let mut line = |l: String| {
        o.push_str(&l);
        o.push('\n');
    };
    let points = s.padding.points();
    let half = points / 2;
    let edge = points - half;
    let canvas = s.layout() == Layout::Canvas;

    line(HEADER.into());
    line(String::new());
    line("[options]".into());
    if canvas {
        line("layout = \"canvas\"".into());
    }
    line(format!("focus_follows_mouse = {}", s.focus_follows_mouse));
    line(format!("mouse_follows_focus = {}", s.mouse_follows_focus));
    let presets: Vec<String> = s.preset_column_widths.iter().map(|w| float(*w)).collect();
    line(format!("preset_column_widths = [{}]", presets.join(", ")));
    line(format!("auto_center = {}", s.auto_center));
    if let Some(v) = s.animation.engine_value() {
        line(format!("animation_speed = {}", float(v)));
    }
    line(format!(
        "create_virtual_workspace_automatically = {}",
        s.virtual_workspaces_enabled && s.create_workspaces_automatically
    ));
    if s.animate_workspace_switch {
        line("virtual_workspace_animations = true".into());
    }
    if !s.resize_modifier.is_empty() {
        line(format!("mouse_resize_modifier = {}", quote(&s.resize_modifier)));
    }

    line(String::new());
    line("[padding]".into());
    for side in ["top", "bottom", "left", "right"] {
        line(format!("{side} = {edge}"));
    }

    line(String::new());
    line("[swipe]".into());
    line(format!("sensitivity = {}", float(s.swipe_sensitivity.clamp(0.1, 2.0))));
    if (s.swipe_deceleration - default_deceleration()).abs() > 1e-9 {
        line(format!("deceleration = {}", float(s.swipe_deceleration.clamp(1.0, 10.0))));
    }
    if s.swipe_stop_at_ends {
        line("continuous = false".into());
    }
    line(String::new());
    line("[swipe.gesture]".into());
    if s.swipe_enabled {
        line(format!("fingers_count = {}", s.swipe_fingers.max(3)));
    }
    line(format!("direction = {}", quote(&format!("{:?}", s.swipe_direction))));
    line(format!("vertical = {}", s.virtual_workspaces_enabled));
    line(String::new());
    line("[swipe.scroll]".into());
    if !s.scroll_modifier.is_empty() {
        line(format!("modifier = {}", quote(&s.scroll_modifier)));
    }

    line(String::new());
    line("[decorations]".into());
    line("workspace_menu_status = false".into());
    line(String::new());
    line("[decorations.active.border]".into());
    line(format!("enabled = {}", s.focus_border_enabled));
    if s.focus_border_enabled {
        line(format!("color = {}", quote(&s.focus_border_color)));
        line("width = 3.0".into());
    }
    if s.dim_inactive_windows {
        // Native dimming: negative opacity, a little deeper in Dark Mode.
        let d = s.dim_strength.clamp(0.05, 0.4);
        line(String::new());
        line("[decorations.inactive.dim]".into());
        line(format!("opacity = {}", float(-d)));
        line(format!("opacity_night = {}", float(-(d + 0.1))));
    }

    line(String::new());
    line("[bindings]".into());
    for (k, v) in bindings(s) {
        let value = if v.len() == 1 {
            quote(&v[0])
        } else {
            format!("[{}]", v.iter().map(|x| quote(x)).collect::<Vec<_>>().join(", "))
        };
        line(format!("{k} = {value}"));
    }

    // An app's width rule is more specific, so it still wins for that app.
    if !canvas {
        line(String::new());
        line("[windows.slat_default_width]".into());
        line("title = \".*\"".into());
        line(format!("width = {}", float(s.default_column_width)));
    }
    if half != 0 {
        line(String::new());
        line("[windows.slat_gaps]".into());
        line("title = \".*\"".into());
        line(format!("horizontal_padding = {half}"));
        line(format!("vertical_padding = {half}"));
    }

    let mut taken: HashSet<String> = ["slat_default_width", "slat_gaps"].map(String::from).into();
    for rule in s.app_rules.iter().filter(|r| !r.bundle_id.is_empty()) {
        let base = safe_name(&rule.bundle_id);
        let mut name = base.clone();
        let mut n = 2;
        while taken.contains(&name) {
            name = format!("{base}_{n}");
            n += 1;
        }
        taken.insert(name.clone());
        line(String::new());
        line(format!("[windows.{name}]"));
        line("title = \".*\"".into());
        line(format!("bundle_id = {}", quote(&rule.bundle_id)));
        match rule.action {
            RuleAction::Float {} => line("floating = true".into()),
            RuleAction::Width { w } => line(format!("width = {}", float(w))),
        }
        if half != 0 {
            line(format!("horizontal_padding = {half}"));
            line(format!("vertical_padding = {half}"));
        }
    }
    o
}

fn default_deceleration() -> f64 {
    Settings::default().swipe_deceleration
}

/// Regenerates engine.toml unless the user edits it by hand.
pub fn apply(s: &Settings) -> std::io::Result<()> {
    if s.use_custom_config_file {
        return Ok(());
    }
    paths::ensure_dirs();
    let path = paths::engine_config();
    let tmp = path.with_extension("toml.tmp");
    fs::write(&tmp, toml(s))?;
    fs::rename(tmp, path)
}

/// Launch-time pass: write the config if missing, regenerate unless custom.
pub fn first_launch(s: &Settings) {
    if !paths::engine_config().exists() || !s.use_custom_config_file {
        let _ = apply(&Settings { use_custom_config_file: false, ..s.clone() });
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::settings::AppRule;

    #[test]
    fn matches_observed_output_byte_for_byte() {
        let s = Settings::parse(include_str!("../tests/fixtures/settings.json"));
        assert_eq!(toml(&s), include_str!("../tests/fixtures/engine.toml"));
    }

    #[test]
    fn width_rule_keeps_default_width_for_other_apps() {
        let mut s = Settings::default();
        s.app_rules = vec![AppRule {
            bundle_id: "com.a.b".into(),
            app_name: "b".into(),
            action: RuleAction::Width { w: 1.0 },
        }];
        let t = toml(&s);
        assert!(t.contains("[windows.slat_default_width]"));
        assert!(t.contains("bundle_id = \"com.a.b\"\nwidth = 1.0\n"));
    }

    #[test]
    fn variants() {
        assert_eq!(float(18.0), "18.0");
        assert_eq!(float(0.35), "0.35");
        assert_eq!(float(1.0), "1.0");
        assert_eq!(safe_name("com.apple.Calculator"), "app_com_apple_calculator");
        let mut s = Settings { animation: crate::settings::Animation::Off, ..Settings::default() };
        s.padding = crate::settings::Padding::None;
        s.layout = Some(Layout::Canvas);
        s.dim_inactive_windows = true;
        s.app_rules = vec![
            AppRule { bundle_id: "com.a.B".into(), app_name: "B".into(), action: RuleAction::Float {} },
            AppRule { bundle_id: "com.a.b".into(), app_name: "b".into(), action: RuleAction::Width { w: 0.66 } },
        ];
        let t = toml(&s);
        assert!(t.contains("layout = \"canvas\"\n"));
        assert!(!t.contains("animation_speed"));
        assert!(!t.contains("slat_default_width") && !t.contains("slat_gaps"));
        assert!(t.contains("[decorations.inactive.dim]\nopacity = -0.15\nopacity_night = -0.25\n"));
        assert!(t.contains("[windows.app_com_a_b]\ntitle = \".*\"\nbundle_id = \"com.a.B\"\nfloating = true\n"));
        assert!(t.contains("[windows.app_com_a_b_2]\ntitle = \".*\"\nbundle_id = \"com.a.b\"\nwidth = 0.66\n"));
        assert!(t.contains("window_focus_west = [\"ctrl + alt - h\", \"ctrl + alt - leftarrow\"]"));
        assert!(t.contains("window_focus_north = "), "canvas keeps plain focus up/down");
        toml::from_str::<toml::Value>(&t).expect("valid toml");

        let s = Settings {
            swipe_deceleration: 7.0,
            swipe_stop_at_ends: true,
            animate_workspace_switch: true,
            dim_inactive_windows: true,
            dim_strength: 0.3,
            focus_border_enabled: true,
            focus_border_color: "#FF375F".into(),
            resize_modifier: "cmd + shift".into(),
            ..Settings::default()
        };
        let t = toml(&s);
        assert!(t.contains("deceleration = 7.0\ncontinuous = false\n"));
        assert!(t.contains("virtual_workspace_animations = true\n"));
        assert!(t.contains("mouse_resize_modifier = \"cmd + shift\"\n"));
        assert!(t.contains("[decorations.active.border]\nenabled = true\ncolor = \"#FF375F\"\nwidth = 3.0\n"));
        assert!(t.contains("opacity = -0.3\nopacity_night = -0.4\n"));
        assert!(t.contains("window_virtualfocus_north = [\"ctrl + alt - k\", \"ctrl + alt - uparrow\"]"), "rows: up/down reach the next row");
        assert!(t.contains("window_balance = \"ctrl + alt - equal\""));
        let parsed = toml::from_str::<toml::Value>(&t).expect("valid toml");
        assert_eq!(parsed["swipe"]["deceleration"].as_float(), Some(7.0));
    }
}
